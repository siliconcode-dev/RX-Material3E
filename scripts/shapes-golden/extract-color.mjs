#!/usr/bin/env node
// Builds the ui-util pieces Google's Color.kt and colorspace package need,
// so the golden reference for Color lerp is Google's own text:
//   - ui-util InlineClassHelper.kt and MathHelpers.kt, verbatim, with each
//     `expect fun` swapped for its JVM actual (the jvmMain sources are not
//     in the sparse checkout)
//   - the compose-runtime @Immutable and @Stable annotations, as empty
//     annotation classes (they only mark classes for the Compose compiler)
// Color.kt, Float16.kt, ui-graphics InlineClassHelper.kt and the
// colorspace package are compiled as they are.
// Usage: extract-color.mjs <androidx-root> <out-dir>
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';

const [root, outDir] = process.argv.slice(2);
const util = 'compose/ui/ui-util/src/commonMain/kotlin/androidx/compose/ui/util';
const read = (p) => readFileSync(join(root, p), 'utf8');

// The JVM actuals of ui-util's expect functions.
const ACTUALS = {
  'public expect fun floatFromBits(bits: Int): Float':
    'public fun floatFromBits(bits: Int): Float = java.lang.Float.intBitsToFloat(bits)',
  'public expect fun doubleFromBits(bits: Long): Double':
    'public fun doubleFromBits(bits: Long): Double = java.lang.Double.longBitsToDouble(bits)',
  'public expect fun Float.fastRoundToInt(): Int':
    'public fun Float.fastRoundToInt(): Int = Math.round(this)',
  'public expect fun Double.fastRoundToInt(): Int':
    'public fun Double.fastRoundToInt(): Int = Math.round(this).toInt()',
};

let inline = read(`${util}/InlineClassHelper.kt`);
for (const [expected, actual] of Object.entries(ACTUALS)) {
  if (!inline.includes(expected)) throw new Error(`InlineClassHelper.kt changed: ${expected}`);
  inline = inline.replace(expected, actual);
}
if (/\bexpect\b\s+fun/.test(inline)) throw new Error('InlineClassHelper.kt has a new expect fun');

writeFileSync(join(outDir, 'InlineClassHelperJvm.kt'), inline);
writeFileSync(join(outDir, 'MathHelpers.kt'), read(`${util}/MathHelpers.kt`));
writeFileSync(
  join(outDir, 'RuntimeAnnotations.kt'),
  `// GENERATED by scripts/shapes-golden/extract-color.mjs. Do not edit.
package androidx.compose.runtime

annotation class Immutable

annotation class Stable
`,
);
console.log(`extracted ui-util helpers and runtime annotations to ${outDir}`);
