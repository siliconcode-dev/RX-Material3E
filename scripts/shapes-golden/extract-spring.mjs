#!/usr/bin/env node
// Builds a compilable Kotlin file from Google's real Compose sources, so the
// golden reference for springs is Google's own text:
//   - FloatSpringSpec, verbatim, from animation-core FloatAnimationSpec.kt
//     (with its FloatAnimationSpec supertype and `override`s removed, since
//     that interface pulls in the rest of the animation library)
//   - the Spring object and MillisToNanos, verbatim
//   - packFloats, unpackFloat1/2 and fastIsFinite, verbatim, from ui-util
// SpringSimulation.kt, SpringEstimation.kt and Preconditions.kt are compiled
// as they are. Usage: extract-spring.mjs <androidx-root> <out-dir>
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';

const [root, outDir] = process.argv.slice(2);
const core =
  'compose/animation/animation-core/src/commonMain/kotlin/androidx/compose/animation/core';
const util = 'compose/ui/ui-util/src/commonMain/kotlin/androidx/compose/ui/util';
const read = (p) => readFileSync(join(root, p), 'utf8');

/** The declaration starting at `start`, through its matching closing brace. */
function block(text, start) {
  const from = text.indexOf(start);
  if (from < 0) throw new Error(`not found: ${start}`);
  let depth = 0;
  for (let i = text.indexOf('{', from); i < text.length; i++) {
    if (text[i] === '{') depth++;
    else if (text[i] === '}' && --depth === 0) return text.slice(from, i + 1);
  }
  throw new Error(`unbalanced: ${start}`);
}

const floatSpec = read(`${core}/FloatAnimationSpec.kt`);
let springSpec = block(floatSpec, 'public class FloatSpringSpec(');
springSpec = springSpec
  .replace(') : FloatAnimationSpec {', ') {')
  .replaceAll('override fun', 'fun');
if (springSpec.includes('FloatAnimationSpec')) throw new Error('FloatSpringSpec changed shape');
const vectorized = read(`${core}/VectorizedAnimationSpec.kt`);
const springObject = block(vectorized, 'public object Spring {');
const animation = read(`${core}/Animation.kt`);
const millis = animation.match(/internal const val MillisToNanos: Long = .*\n/)[0];

const inline = read(`${util}/InlineClassHelper.kt`);
const math = read(`${util}/MathHelpers.kt`);
const utilFns = [
  block(inline, 'public inline fun packFloats('),
  block(inline, 'public inline fun unpackFloat1('),
  block(inline, 'public inline fun unpackFloat2('),
  block(math, 'public inline fun Float.fastIsFinite()'),
  block(math, 'public inline fun Double.fastIsFinite()'),
];

writeFileSync(
  join(outDir, 'SpringExtract.kt'),
  `// GENERATED by scripts/shapes-golden/extract-spring.mjs. Do not edit.
package androidx.compose.animation.core

// ---- Verbatim from animation-core ----
${millis}
${springObject}

${springSpec}
`,
);
writeFileSync(
  join(outDir, 'UiUtilExtract.kt'),
  `// GENERATED by scripts/shapes-golden/extract-spring.mjs. Do not edit.
@file:Suppress("NOTHING_TO_INLINE")
package androidx.compose.ui.util

// The JVM actual of ui-util's expect floatFromBits.
fun floatFromBits(bits: Int): Float = Float.fromBits(bits)

// ---- Verbatim from ui-util ----
${utilFns.join('\n\n')}
`,
);
console.log(`extracted FloatSpringSpec, Spring and ui-util helpers to ${outDir}`);
