#!/usr/bin/env node
// Builds a compilable Kotlin file from Google's real sources, so the golden
// reference for MaterialShapes is Google's own text, not a copy typed by hand:
//   - the MaterialShapes class body, verbatim, from material3 MaterialShapes.kt
//   - Matrix get/set, map(Offset), rotateZ and scale, verbatim, from ui-graphics Matrix.kt
//   - RoundedPolygon.transformed(Matrix), verbatim, from material3 internal/ShapeUtil.kt
// plus small stand-ins for Compose types those pieces use (Offset, fastMap,
// fastIsFinite). Usage: extract-material-shapes.mjs <androidx-root> <out.kt>
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';

const [root, out] = process.argv.slice(2);
const read = (p) => readFileSync(join(root, p), 'utf8');

/** The text of the declaration starting at `start`, through its matching closing brace. */
function block(text, start) {
  const from = text.indexOf(start);
  if (from < 0) throw new Error(`not found: ${start}`);
  let depth = 0;
  for (let i = text.indexOf('{', from); i < text.length; i++) {
    if (text[i] === '{') depth++;
    else if (text[i] === '}' && --depth === 0) return text.slice(from, i + 1);
  }
  throw new Error(`unbalanced: ${start}`);
}

const shapes = read(
  'compose/material3/material3/src/commonMain/kotlin/androidx/compose/material3/MaterialShapes.kt',
);
const matrix = read(
  'compose/ui/ui-graphics/src/commonMain/kotlin/androidx/compose/ui/graphics/Matrix.kt',
);
const shapeUtil = read(
  'compose/material3/material3/src/commonMain/kotlin/androidx/compose/material3/internal/ShapeUtil.kt',
);

const materialShapes = block(shapes, 'public sealed class MaterialShapes');
const matrixMembers = [
  'public inline operator fun get(row: Int, column: Int): Float',
  'public inline operator fun set(row: Int, column: Int, v: Float)',
].map((s) =>
  s.includes('get(')
    ? matrix.slice(matrix.indexOf(s), matrix.indexOf('\n', matrix.indexOf(s)))
    : block(matrix, s),
);
const matrixMethods = [
  'public fun map(point: Offset): Offset',
  'public fun rotateZ(degrees: Float)',
  'public fun scale(x: Float = 1f',
].map((s) => block(matrix, s));
const transformedFrom = shapeUtil.indexOf(
  'internal fun RoundedPolygon.transformed(matrix: Matrix)',
);
const transformed = shapeUtil.slice(
  transformedFrom,
  shapeUtil.indexOf('\n}\n', transformedFrom) + 2,
);

const kotlin = `// GENERATED by scripts/shapes-golden/extract-material-shapes.mjs. Do not edit.
@file:Suppress("NOTHING_TO_INLINE")
package androidx.compose.material3

import androidx.graphics.shapes.CornerRounding
import androidx.graphics.shapes.RoundedPolygon
import androidx.graphics.shapes.TransformResult
import androidx.graphics.shapes.circle
import androidx.graphics.shapes.rectangle
import androidx.graphics.shapes.star
import kotlin.math.PI
import kotlin.math.atan2
import kotlin.math.cos
import kotlin.math.sin
import kotlin.math.sqrt

// ---- Stand-ins for Compose types ----
annotation class ExperimentalMaterial3ExpressiveApi

data class Offset(val x: Float, val y: Float) {
    operator fun minus(o: Offset) = Offset(x - o.x, y - o.y)
    operator fun plus(o: Offset) = Offset(x + o.x, y + o.y)
    operator fun times(f: Float) = Offset(x * f, y * f)
    fun getDistance() = sqrt(x * x + y * y)
    companion object { val Zero = Offset(0f, 0f) }
}

inline fun <T, R> List<T>.fastMap(transform: (T) -> R): List<R> = map(transform)

inline fun Float.fastIsFinite(): Boolean = isFinite()

// ---- Verbatim from ui-graphics Matrix.kt ----
class Matrix(
    val values: FloatArray =
        floatArrayOf(1f, 0f, 0f, 0f, 0f, 1f, 0f, 0f, 0f, 0f, 1f, 0f, 0f, 0f, 0f, 1f)
) {
${[...matrixMembers, ...matrixMethods].join('\n\n')}
}

// ---- Verbatim from material3 internal/ShapeUtil.kt ----
${transformed}

// ---- Verbatim from material3 MaterialShapes.kt ----
${materialShapes}
`;
writeFileSync(out, kotlin);
console.log(`extracted MaterialShapes (${materialShapes.split('\n').length} lines) to ${out}`);
